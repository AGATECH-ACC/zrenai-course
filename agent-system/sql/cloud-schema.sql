CREATE SCHEMA IF NOT EXISTS zrenai_course;
REVOKE ALL ON SCHEMA zrenai_course FROM PUBLIC, anon, authenticated;
SET search_path TO zrenai_course, pg_catalog;

CREATE TABLE IF NOT EXISTS users (
 id TEXT PRIMARY KEY, username TEXT NOT NULL UNIQUE,
 password_hash TEXT NOT NULL, kind TEXT NOT NULL CHECK(kind IN ('admin','agent')),
 agent_id TEXT UNIQUE, active BIGINT NOT NULL DEFAULT 1, created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id),
 csrf TEXT NOT NULL, expires_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS agents (
 id TEXT PRIMARY KEY, code TEXT UNIQUE NOT NULL, name TEXT NOT NULL, contact TEXT NOT NULL,
 parent_id TEXT REFERENCES agents(id), role TEXT NOT NULL CHECK(role IN ('sales','partner')),
 active BIGINT NOT NULL DEFAULT 1, personal_sales BIGINT NOT NULL DEFAULT 0,
 promoted_at TEXT, sales_year BIGINT NOT NULL, created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS products (
 id TEXT PRIMARY KEY, name TEXT NOT NULL, family TEXT NOT NULL, price BIGINT,
 participants BIGINT, token_gift BIGINT NOT NULL, delivery_bp BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS policies (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, config TEXT NOT NULL, created_at TEXT NOT NULL,
 actor TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS customers (
 id TEXT PRIMARY KEY, account TEXT NOT NULL UNIQUE, name TEXT NOT NULL, created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS orders (
 id TEXT PRIMARY KEY, number TEXT UNIQUE NOT NULL, agent_id TEXT NOT NULL REFERENCES agents(id),
 customer_id TEXT NOT NULL REFERENCES customers(id), product_id TEXT NOT NULL REFERENCES products(id),
 amount BIGINT NOT NULL CHECK(amount>0), tax BIGINT NOT NULL DEFAULT 0,
 status TEXT NOT NULL CHECK(status IN ('draft','paid','refunded','cancelled')),
 note TEXT NOT NULL, participants BIGINT NOT NULL, created_at TEXT NOT NULL,
 paid_at TEXT, refund_at TEXT, payment_ref TEXT, refund_ref TEXT, policy_id BIGINT REFERENCES policies(id),
 role_at_sale TEXT, delivery_amount BIGINT NOT NULL DEFAULT 0,
 gift_amount BIGINT NOT NULL DEFAULT 0, snapshot TEXT, created_by TEXT NOT NULL,
 request_key TEXT UNIQUE NOT NULL, sales_year BIGINT);
CREATE TABLE IF NOT EXISTS commissions (
 id TEXT PRIMARY KEY, order_id TEXT NOT NULL REFERENCES orders(id),
 agent_id TEXT NOT NULL REFERENCES agents(id), level BIGINT NOT NULL,
 amount BIGINT NOT NULL, rate_bp BIGINT NOT NULL,
 status TEXT NOT NULL CHECK(status IN ('pending','approved','paid','reversed')),
 kind TEXT NOT NULL CHECK(kind IN ('earning','clawback')),
 created_at TEXT NOT NULL, approved_at TEXT, payout_id TEXT, reversal_of TEXT UNIQUE,
 UNIQUE(order_id,agent_id,kind));
CREATE TABLE IF NOT EXISTS token_ledger (
 id TEXT PRIMARY KEY, customer_id TEXT NOT NULL REFERENCES customers(id),
 order_id TEXT NOT NULL REFERENCES orders(id), amount BIGINT NOT NULL,
 kind TEXT NOT NULL CHECK(kind IN ('gift','reversal')), created_at TEXT NOT NULL,
 UNIQUE(order_id,kind));
CREATE TABLE IF NOT EXISTS payouts (
 id TEXT PRIMARY KEY, agent_id TEXT NOT NULL REFERENCES agents(id), amount BIGINT NOT NULL,
 reference TEXT UNIQUE NOT NULL, created_at TEXT NOT NULL, actor TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor TEXT NOT NULL, action TEXT NOT NULL,
 entity_id TEXT NOT NULL, detail TEXT NOT NULL, created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS inquiries (
 id TEXT PRIMARY KEY, agent_id TEXT NOT NULL REFERENCES agents(id),
 product_id TEXT NOT NULL REFERENCES products(id), customer_name TEXT NOT NULL,
 contact TEXT NOT NULL, participants BIGINT NOT NULL, message TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'new' CHECK(status IN ('new','contacted','converted','closed')),
 followup TEXT NOT NULL DEFAULT '', order_id TEXT UNIQUE REFERENCES orders(id),
 request_key TEXT NOT NULL UNIQUE, created_at TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS inquiries_agent ON inquiries(agent_id,created_at);
CREATE INDEX IF NOT EXISTS orders_agent ON orders(agent_id,created_at);
CREATE INDEX IF NOT EXISTS commission_agent_status ON commissions(agent_id,status);
CREATE INDEX IF NOT EXISTS agents_parent ON agents(parent_id);

CREATE TABLE IF NOT EXISTS supabase_links (
 user_id TEXT PRIMARY KEY REFERENCES users(id), auth_id TEXT NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS supabase_sessions (
 token_hash TEXT PRIMARY KEY REFERENCES sessions(token_hash) ON DELETE CASCADE,
 access_token TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS request_limits (
 bucket TEXT PRIMARY KEY, hits BIGINT NOT NULL, started_at BIGINT NOT NULL);
CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower ON users(lower(username));
